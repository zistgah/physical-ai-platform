import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { REACHABLE } from '../../site/components/core/module-registry.js';
import { createComputePlan, validateComputeResult, validateComputeResultAsync } from './module.js';
const api=REACHABLE['drop-in/hosted-compute/module.js'];
assert.ok(api,'new package is registered in canonical module registry');
const inputHash='1'.repeat(64);
const plan=api.createComputePlan({projectId:'PAP-INTEGRATION',configurationId:'CFG-1',runId:'RUN-1',solverId:'mms-poisson',backendId:'numpy-scipy',domain:'sparse',accelerator:'cpu',requirements:['REQ-1'],inputHash,resources:{maxWallSeconds:30,maxMemoryGiB:2,maxGpuCount:0},tolerance:0.01});
assert.equal(plan.status,'READY');
const incomplete=api.validateComputeResult({schema:'pap.hosted-compute-result/1.0',status:'COMPLETED'},plan,{digestVerified:true});
assert.equal(incomplete.status,'HOLD');
assert.equal(incomplete.evidenceDraft,null);
const result={schema:'pap.hosted-compute-result/1.0',planId:plan.plan.planId,projectId:'PAP-INTEGRATION',configurationId:'CFG-1',runId:'RUN-1',solverId:'mms-poisson',backendId:'numpy-scipy',backendVersion:'1.17.0',metadata:{platform:'Physical AI Platform',iteration:50,license:'GPL-3.0-only',copyright:'Copyright © 1993-2026 Abhishek Choudhary. All rights reserved.',notebook:'notebooks/PAP_Hosted_Compute_Backends.ipynb'},status:'COMPLETED',runtime:'Python 3.12',device:'CPU',precision:'float64',inputHash,outputHash:'2'.repeat(64),startedAt:'2026-10-30T00:00:00Z',finishedAt:'2026-10-30T00:00:01Z',executionMode:'COLAB_HOSTED',checks:[{id:'MMS',passed:true}],metrics:{relativeL2Error:0.001,relativeResidual:1e-12},validation:{passed:true,error:0.001,method:'manufactured-solution'},resourceUsage:{wallSeconds:1,peakMemoryGiB:0.4,gpuCount:0}};
const accepted=api.validateComputeResult(result,plan,{digestVerified:true});
assert.equal(accepted.status,'ACCEPTED');
assert.equal(accepted.evidenceDraft.method,'SIMULATION');
assert.equal(accepted.evidenceDraft.fidelity,'UNVERIFIED');
assert.equal(accepted.evidenceDraft.claims.hil,false);
assert.equal(accepted.evidenceDraft.claims.l5,false);
// Cross-language fixture was generated by executing the Python notebook. This
// verifies that Python's canonical JSON/SHA-256 format is accepted by the JS
// Web Crypto validator, not merely by a JS-generated fixture.
const notebookResult = JSON.parse(await readFile(new URL('./fixtures/hosted-compute-result.sample.json', import.meta.url), 'utf8'));
const notebookPlan = createComputePlan({
  projectId:notebookResult.projectId, configurationId:notebookResult.configurationId,
  runId:notebookResult.runId, solverId:notebookResult.solverId, backendId:notebookResult.backendId,
  domain:({pytorch:'tensor',jax:'tensor',numba:'jit',cupy:'array',pyamg:'sparse','numpy-scipy':'sparse'})[notebookResult.backendId] || 'sparse',
  accelerator:notebookResult.device.startsWith('cuda')?'nvidia-gpu':'cpu',
  requirements:['REQ-NUMERICAL-VERIFICATION','REQ-TRACEABILITY'], inputHash:notebookResult.inputHash,
  resources:{maxWallSeconds:3600,maxMemoryGiB:12,maxGpuCount:notebookResult.device.startsWith('cuda')?1:0},
  tolerance:0.002, executionMode:notebookResult.executionMode, createdAt:notebookResult.startedAt
});
assert.equal(notebookPlan.status,'READY');
const notebookAccepted=await validateComputeResultAsync(notebookResult,notebookPlan);
assert.equal(notebookAccepted.status,'ACCEPTED');
assert.equal(notebookAccepted.evidenceDraft.method,'SIMULATION');
assert.equal(notebookAccepted.evidenceDraft.fidelity,'UNVERIFIED');
assert.equal(notebookAccepted.evidenceDraft.claims.hil,false);
console.log('Hosted Compute package integration PASS: registry -> plan -> result validation -> simulation-only evidence draft; Python notebook fixture digest verified in JavaScript.');
