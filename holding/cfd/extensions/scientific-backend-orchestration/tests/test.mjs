import assert from 'node:assert/strict';
import { createBackendRegistry, validateBackendManifest, BACKEND_ORCHESTRATION_CONTRACT } from '../module.js';
const manifest = { id:'test.solver', name:'Test Solver', version:'1.0.0', provider:'fixture', license:'MIT', executionModes:['COLAB'], capabilities:[{domain:'incompressible-flow',dimensions:2}] };
assert.equal(validateBackendManifest(null).outcome,'HOLD');
assert.equal(validateBackendManifest({...manifest,license:'UNKNOWN'}).code,'LICENSE_UNKNOWN');
assert.equal(validateBackendManifest({...manifest,executionModes:['MAGIC']}).code,'EXECUTION_MODE_INVALID');
const registry=createBackendRegistry();
assert.equal(registry.register(manifest,{}).code,'ADAPTER_INTERFACE_INVALID');
const adapter={probe:async()=>({available:true}),execute:async({job})=>({outcome:'OK',fieldCount:job.dimensions})};
assert.equal(registry.register(manifest,adapter).outcome,'OK');
assert.equal(registry.register(manifest,adapter).code,'BACKEND_DUPLICATE');
assert.equal((await registry.discover({domain:'incompressible-flow',dimensions:2})).candidates[0].available,true);
assert.equal((await registry.discover({domain:'incompressible-flow',dimensions:3})).candidates.length,0);
assert.equal((await registry.execute({},{})).code,'JOB_INVALID');
const job={id:'job-1',domain:'incompressible-flow',dimensions:2,subjectRefs:['sir:component:1'],configurationRef:'config:rev:7'};
assert.equal((await registry.execute(job,{})).code,'BACKEND_NOT_SELECTED');
assert.equal((await registry.execute({...job,subjectRefs:[]},{backendId:manifest.id,executionMode:'COLAB'})).code,'SUBJECT_BINDING_MISSING');
assert.equal((await registry.execute(job,{backendId:manifest.id,executionMode:'BROWSER'})).code,'EXECUTION_MODE_UNSUPPORTED');
const result=await registry.execute(job,{backendId:manifest.id,executionMode:'COLAB'});
assert.equal(result.executionState,'EXECUTED_UNVERIFIED');
assert.equal(result.promotionAllowed,false);
assert.equal(result.evidenceProposal.verificationState,'UNVERIFIED');
const failing=createBackendRegistry();
failing.register({...manifest,id:'throws'}, {probe:async()=>({available:true}),execute:async()=>{throw new Error('boom')}});
assert.equal((await failing.execute({...job},{backendId:'throws',executionMode:'COLAB'})).code,'BACKEND_EXECUTION_FAILED');
const bad=failing;
assert.equal((await bad.discover({domain:'',dimensions:2})).code,'DISCOVERY_REQUEST_INVALID');
const probeFail=createBackendRegistry();
probeFail.register({...manifest,id:'probe-throws'}, {probe:async()=>{throw new Error('probe boom')},execute:async()=>({outcome:'OK'})});
const probeResult=await probeFail.discover({domain:'incompressible-flow',dimensions:2});
assert.equal(probeResult.candidates[0].available,false);
assert.equal(probeResult.candidates[0].reason,'PROBE_FAILED');
const badResult=createBackendRegistry();
badResult.register({...manifest,id:'bad-result'}, {probe:async()=>({available:true}),execute:async()=>({status:'success'})});
assert.equal((await badResult.execute(job,{backendId:'bad-result',executionMode:'COLAB'})).code,'BACKEND_RESULT_INVALID');
const unavailable=createBackendRegistry();
unavailable.register({...manifest,id:'unavailable'}, {probe:async()=>({available:false,reason:'no runtime'}),execute:async()=>({outcome:'OK'})});
assert.equal((await unavailable.execute(job,{backendId:'unavailable',executionMode:'COLAB'})).code,'BACKEND_UNAVAILABLE');
assert.equal((await probeFail.execute(job,{backendId:'probe-throws',executionMode:'COLAB'})).code,'BACKEND_PROBE_FAILED');
assert.equal(BACKEND_ORCHESTRATION_CONTRACT.ownsCanonicalGraph,false);
assert.equal(BACKEND_ORCHESTRATION_CONTRACT.autoPromotesEvidence,false);
console.log('BACKEND ORCHESTRATION PASS: manifest validation; license gate; adapter contract; duplicate protection; capability discovery; canonical bindings; execution-mode gate; preflight availability gate; probe/execute exception handling; invalid result rejection; no evidence promotion');
